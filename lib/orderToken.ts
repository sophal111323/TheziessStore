import crypto from "crypto";

const ORDER_TOKEN_PATTERN = /^[0-9a-f]{64}$/i;

/** Placeholder playerUid stored for voucher orders (app/api/orders/route.ts). */
const NON_RECOVERABLE_UIDS = new Set(["", "roblox-user"]);

/**
 * Resolves the HMAC secret. Empty / whitespace-only values count as unset.
 * Returns "" when nothing is configured (callers must fail closed).
 */
function getOrderTokenSecret(): string {
  const primary = (process.env.ORDER_LOOKUP_SECRET ?? "").trim();
  if (primary) return primary;
  return (process.env.ADMIN_JWT_SECRET ?? "").trim();
}

/** True when a non-empty secret is available for order tokens. */
export function isOrderTokenConfigured(): boolean {
  return getOrderTokenSecret().length > 0;
}

/**
 * Generates an HMAC-SHA256 token for secure order lookup.
 *
 * This prevents unauthorized enumeration of order details by requiring
 * a cryptographically signed token that can only be generated by the server.
 *
 * @param orderNumber - The order number to generate a token for
 * @returns HMAC token as hex string
 * @throws when neither ORDER_LOOKUP_SECRET nor ADMIN_JWT_SECRET is configured
 */
export function generateOrderToken(orderNumber: string): string {
  const secret = getOrderTokenSecret();

  if (!secret) {
    throw new Error("ORDER_LOOKUP_SECRET or ADMIN_JWT_SECRET must be configured");
  }

  const hmac = crypto.createHmac("sha256", secret);
  hmac.update(orderNumber.trim().toUpperCase());
  return hmac.digest("hex");
}

/**
 * Verifies an HMAC-SHA256 token for secure order lookup using timing-safe comparison.
 *
 * @param orderNumber - The order number to verify
 * @param token - The HMAC token to verify
 * @returns true if token is valid, false otherwise
 */
export function verifyOrderToken(orderNumber: string, token: string | null | undefined): boolean {
  if (!token || !ORDER_TOKEN_PATTERN.test(token)) {
    return false;
  }

  try {
    const expected = Buffer.from(generateOrderToken(orderNumber), "hex");
    const provided = Buffer.from(token, "hex");

    if (expected.length !== provided.length) {
      return false;
    }

    // Timing-safe comparison to prevent timing attacks
    return crypto.timingSafeEqual(expected, provided);
  } catch {
    // Secret not configured
    return false;
  }
}

/** Normalizes a player UID for comparison: trim, lowercase, strip all whitespace. */
export function normalizePlayerUid(uid: string): string {
  return uid.trim().toLowerCase().replace(/\s+/g, "");
}

/**
 * Whether a (normalized) stored playerUid may be used to recover an order token.
 * Empty values and the voucher placeholder are guessable, so they are not recoverable.
 */
export function isRecoverablePlayerUid(normalized: string): boolean {
  return !NON_RECOVERABLE_UIDS.has(normalized);
}
